  <section class="clause" id="informacion">
    <h2><span class="num">01</span> Información que recopilamos</h2>
    <p>Recopilamos las siguientes categorías de información para poder ofrecerte la Aplicación:</p>
    <h3>Datos de cuenta y progreso</h3>
    <ul>
      <li><strong>Identificador de usuario y nombre de usuario:</strong> para reconocer tu perfil y permitir el juego.</li>
      <li><strong>Progreso de juego:</strong> niveles completados, logros y estadísticas, almacenados para sincronizar tu experiencia entre sesiones o dispositivos.</li>
    </ul>
    <h3>Datos de compra</h3>
    <p>
      Cuando realizas una compra dentro de la Aplicación, <strong>Google Play Billing</strong> procesa el
      pago directamente. Nosotros únicamente recibimos la confirmación de la transacción (producto adquirido
      y estado de la compra) para acreditar el contenido correspondiente en tu cuenta de juego.
    </p>
    <h3>Datos de uso</h3>
    <p>
      Información general sobre tu interacción con la Aplicación —niveles jugados, monedas obtenidas, tiempo
      de sesión, tasa de errores o fallos— que utilizamos con fines estadísticos y de mejora del producto.
    </p>
    <h3>Datos del dispositivo</h3>
    <p>
      Información técnica generada automáticamente por tu dispositivo y por los servicios de terceros
      descritos en la sección 5, como modelo de dispositivo, sistema operativo, identificador de
      publicidad, idioma, zona horaria y registros de fallos (crash logs).
    </p>
  </section>

  <section class="clause" id="uso">
    <h2><span class="num">02</span> Cómo usamos la información</h2>
    <p>Utilizamos la información recopilada para los siguientes propósitos:</p>
    <ul>
      <li>Guardar y sincronizar tu progreso de juego entre sesiones.</li>
      <li>Procesar, verificar y acreditar las compras realizadas dentro de la Aplicación.</li>
      <li>Diagnosticar errores, corregir fallos y mejorar el rendimiento y la estabilidad del juego.</li>
      <li>Analizar patrones de uso agregados para mejorar el diseño y el balance del juego.</li>
      <li>Cumplir con obligaciones legales y hacer valer nuestros términos de servicio.</li>
    </ul>
    <p>No utilizamos tu información para tomar decisiones automatizadas que produzcan efectos legales sobre ti.</p>
  </section>

  <section class="clause" id="base-legal">
    <h2><span class="num">03</span> Base legal del tratamiento</h2>
    <p>Cuando la normativa aplicable lo exige (por ejemplo, el Reglamento General de Protección de Datos de la Unión Europea), tratamos tu información con base en:</p>
    <ul>
      <li><strong>Ejecución de un contrato:</strong> para prestarte los servicios de la Aplicación que solicitas, incluidas las compras dentro de la app.</li>
      <li><strong>Interés legítimo:</strong> para mantener la seguridad, prevenir el fraude y mejorar el producto.</li>
      <li><strong>Consentimiento:</strong> cuando corresponda, por ejemplo para ciertos identificadores de publicidad, pudiendo retirarlo en cualquier momento desde la configuración de tu dispositivo.</li>
      <li><strong>Cumplimiento de obligaciones legales:</strong> cuando debamos conservar o entregar información a una autoridad competente.</li>
    </ul>
  </section>

  <section class="clause" id="compras">
    <h2><span class="num">04</span> Compras dentro de la aplicación</h2>
    <p>
      Todas las compras dentro de la Aplicación son procesadas por <strong>Google Play Billing</strong>.
      No almacenamos números de tarjeta, datos bancarios ni ninguna otra información financiera en
      nuestros propios servidores. La transacción de pago se gestiona íntegramente por Google, conforme a
      sus propios <a href="https://policies.google.com/terms" target="_blank" rel="noopener">Términos del Servicio</a>
      y <a href="https://policies.google.com/privacy" target="_blank" rel="noopener">Política de Privacidad</a>.
    </p>
    <p>Las compras dentro de la app no son reembolsables por nosotros directamente; las solicitudes de reembolso deben gestionarse a través de Google Play siguiendo sus políticas.</p>
  </section>

  <section class="clause" id="terceros">
    <h2><span class="num">05</span> Servicios de terceros</h2>
    <p>La Aplicación se apoya en los siguientes servicios de terceros, cada uno sujeto a su propia política de privacidad:</p>
    <ul>
      <li><strong>Google Play Services:</strong> distribución, autenticación, facturación y servicios base de Android.</li>
      <li><strong>Unity Technologies:</strong> motor de juego y, si está habilitado, analítica de uso y reporte de fallos (Unity Analytics / Unity Crash Reporting).</li>
    </ul>
    <p>
      Te recomendamos revisar las políticas de privacidad de
      <a href="https://policies.google.com/privacy" target="_blank" rel="noopener">Google</a> y de
      <a href="https://unity.com/legal/privacy-policy" target="_blank" rel="noopener">Unity Technologies</a>
      para entender cómo tratan tu información.
    </p>
  </section>

  <section class="clause" id="comparticion">
    <h2><span class="num">06</span> Con quién compartimos datos</h2>
    <p>No vendemos tu información personal. Solo la compartimos en los siguientes casos:</p>
    <ul>
      <li>Con los proveedores de servicios mencionados en la sección 5, en la medida necesaria para que la Aplicación funcione.</li>
      <li>Cuando la ley, una orden judicial o un proceso legal válido nos obligue a hacerlo.</li>
      <li>Para proteger los derechos, la propiedad o la seguridad de nuestros usuarios, del público o de NelsonDJCR.</li>
      <li>En caso de fusión, adquisición o venta de activos, sujeto a que el receptor mantenga protecciones equivalentes.</li>
    </ul>
  </section>

  <section class="clause" id="retencion">
    <h2><span class="num">07</span> Retención de datos</h2>
    <p>
      Conservamos tu información de cuenta y progreso mientras mantengas una cuenta activa en la Aplicación.
      Si solicitas la eliminación de tu cuenta, borraremos o anonimizaremos tus datos personales dentro de
      un plazo razonable, salvo que debamos conservar cierta información para cumplir obligaciones legales,
      resolver disputas o hacer cumplir nuestros acuerdos.
    </p>
  </section>

  <section class="clause" id="seguridad">
    <h2><span class="num">08</span> Seguridad de la información</h2>
    <p>
      Aplicamos medidas técnicas y organizativas razonables para proteger tu información contra acceso,
      alteración, divulgación o destrucción no autorizados. Sin embargo, ningún método de transmisión por
      Internet ni de almacenamiento electrónico es completamente seguro, por lo que no podemos garantizar
      su seguridad absoluta.
    </p>
  </section>

  <section class="clause" id="derechos">
    <h2><span class="num">09</span> Tus derechos y opciones</h2>
    <p>Dependiendo de tu ubicación, puedes tener derecho a:</p>
    <ul>
      <li><strong>Acceder</strong> a la información personal que tenemos sobre ti.</li>
      <li><strong>Rectificar</strong> datos inexactos o incompletos.</li>
      <li><strong>Solicitar la eliminación</strong> de tu cuenta y datos asociados.</li>
      <li><strong>Oponerte u limitar</strong> ciertos tratamientos de tus datos.</li>
      <li><strong>Portabilidad</strong> de tus datos en un formato estructurado, cuando sea técnicamente posible.</li>
      <li><strong>Retirar tu consentimiento</strong> en cualquier momento, sin afectar la licitud del tratamiento previo.</li>
    </ul>
    <div class="note">
      Para ejercer cualquiera de estos derechos, escríbenos a través del correo indicado en la sección de
      Contacto. Responderemos dentro de los plazos que establezca la normativa aplicable.
    </div>
  </section>

  <section class="clause" id="transferencias">
    <h2><span class="num">10</span> Transferencias internacionales</h2>
    <p>
      Tu información puede ser almacenada y procesada en servidores ubicados fuera de tu país de residencia,
      incluidos los de nuestros proveedores como Google y Unity Technologies. Cuando esto ocurra, exigimos
      que dichos proveedores mantengan garantías adecuadas de protección de datos conforme a la normativa
      aplicable.
    </p>
  </section>

  <section class="clause" id="menores">
    <h2><span class="num">11</span> Privacidad de menores</h2>
    <p>
      La Aplicación no está dirigida a menores de 13 años y no recopilamos intencionalmente información
      personal de niños menores de esa edad. Si tienes motivos para creer que un menor de 13 años nos ha
      proporcionado información personal, contáctanos para que podamos eliminarla.
    </p>
  </section>

  <section class="clause" id="cambios">
    <h2><span class="num">12</span> Cambios a esta política</h2>
    <p>
      Podemos actualizar esta Política de Privacidad periódicamente para reflejar cambios en nuestras
      prácticas o por motivos legales, operativos o regulatorios. Publicaremos cualquier cambio en esta
      misma página junto con una nueva fecha de "Última actualización". Te recomendamos revisarla
      periódicamente; el uso continuado de la Aplicación tras una actualización constituye tu aceptación
      de los cambios.
    </p>
  </section>

